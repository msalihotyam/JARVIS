"""Deterministic code map of jarvis/ and scripts/ (stdlib only, parse-only).

Writes build/codemap/MAP.md (compact, one line per symbol, grouped by package)
and build/codemap/map.json (same facts plus the derived "imported_by" edges).
Source files are only read, never imported; no network, no model call.
Same tree in -> byte-identical files out (sorted everywhere, no timestamps).

    python scripts/code_map.py [--root DIR] [--out DIR]
"""
from __future__ import annotations

import argparse
import ast
import json
import sys
from pathlib import Path

ROOTS = ("jarvis", "scripts")
MAX_DOC = 100
MAX_SIG = 110


def _first_line(node: ast.AST) -> str:
    doc = ast.get_docstring(node)  # type: ignore[arg-type]
    if not doc:
        return ""
    line = doc.strip().splitlines()[0].strip()
    return line if len(line) <= MAX_DOC else line[: MAX_DOC - 1] + "…"


def _clip(text: str) -> str:
    return text if len(text) <= MAX_SIG else text[: MAX_SIG - 1] + "…"


def _symbols(tree: ast.Module) -> tuple[list[dict], list[dict]]:
    classes, funcs = [], []
    for node in tree.body:
        name = getattr(node, "name", "")
        if not name or name.startswith("_"):
            continue
        if isinstance(node, ast.ClassDef):
            parts = [ast.unparse(b) for b in node.bases] + [ast.unparse(k) for k in node.keywords]
            sig = f"class {name}({', '.join(parts)})" if parts else f"class {name}"
            classes.append({"name": name, "signature": _clip(sig), "line": node.lineno, "doc": _first_line(node)})
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            kw = "async def" if isinstance(node, ast.AsyncFunctionDef) else "def"
            ret = f" -> {ast.unparse(node.returns)}" if node.returns else ""
            sig = f"{kw} {name}({ast.unparse(node.args)}){ret}"
            funcs.append({"name": name, "signature": _clip(sig), "line": node.lineno, "doc": _first_line(node)})
    return classes, funcs


def _dotted_names(rel: str) -> list[str]:
    parts = rel[:-3].split("/")
    if parts[-1] == "__init__":
        parts.pop()
    names = [".".join(parts)]
    if parts[0] == "scripts" and len(parts) == 2:  # scripts import each other as top-level names
        names.append(parts[1])
    return names


def _import_names(tree: ast.Module, rel: str) -> set[str]:
    pkg = rel.split("/")[:-1]
    found: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            found.update(a.name for a in node.names)
        elif isinstance(node, ast.ImportFrom):
            base = node.module or ""
            if node.level:
                keep = pkg[: len(pkg) - (node.level - 1)]
                base = ".".join(keep + ([node.module] if node.module else []))
            found.update(f"{base}.{a.name}" if base else a.name for a in node.names)
    return found


def _resolve(name: str, table: dict[str, str]) -> str | None:
    parts = name.split(".")
    for i in range(len(parts), 0, -1):
        hit = table.get(".".join(parts[:i]))
        if hit:
            return hit
    return None


def build(root: Path, roots: tuple[str, ...] = ROOTS) -> dict:
    files = sorted(
        p.relative_to(root).as_posix()
        for r in roots
        for p in (root / r).rglob("*.py")
        if "__pycache__" not in p.parts
    )
    table = {n: rel for rel in files for n in _dotted_names(rel)}
    modules: dict[str, dict] = {}
    unparsed: list[dict] = []
    trees: dict[str, ast.Module] = {}
    for rel in files:
        data = (root / rel).read_bytes()
        lines = data.count(b"\n") + (1 if data and not data.endswith(b"\n") else 0)
        try:
            tree = ast.parse(data, filename=rel)
        except (SyntaxError, ValueError, RecursionError, MemoryError) as exc:
            msg = getattr(exc, "msg", None) or type(exc).__name__
            unparsed.append({"path": rel, "lines": lines, "error": f"{msg} (line {getattr(exc, 'lineno', None) or '?'})"})
            continue
        trees[rel] = tree
        classes, funcs = _symbols(tree)
        modules[rel] = {"lines": lines, "doc": _first_line(tree), "classes": classes, "functions": funcs,
                        "imports": [], "imported_by": []}
    for rel, tree in trees.items():
        deps = {_resolve(n, table) for n in _import_names(tree, rel)}
        modules[rel]["imports"] = sorted(d for d in deps if d and d != rel)
    for rel, mod in modules.items():
        for dep in mod["imports"]:
            if dep in modules:
                modules[dep]["imported_by"].append(rel)
    for mod in modules.values():
        mod["imported_by"].sort()
    return {"version": 1, "roots": list(roots), "modules": modules, "unparsed": unparsed}


def render(data: dict) -> str:
    out = ["# CODE MAP (generated by scripts/code_map.py, do not edit)",
           f"modules: {len(data['modules'])}  unparsed: {len(data['unparsed'])}",
           "format: path [lines] doc / imports: in-repo modules / class|def signature @line - doc (public, top level)"]
    entries = [(rel, "mod") for rel in data["modules"]] + [(u["path"], "bad") for u in data["unparsed"]]
    last_dir = None
    for rel, kind in sorted(entries, key=lambda e: (e[0].rpartition("/")[0], e[0])):  # by package, then name
        pdir = rel.rpartition("/")[0]
        if pdir != last_dir:
            out += ["", f"## {pdir}/"]
            last_dir = pdir
        if kind == "bad":
            u = next(x for x in data["unparsed"] if x["path"] == rel)
            out.append(f"- {rel} [{u['lines']}] UNPARSED: {u['error']}")
            continue
        m = data["modules"][rel]
        out.append(f"- {rel} [{m['lines']}]" + (f" {m['doc']}" if m["doc"] else ""))
        if m["imports"]:
            out.append("  imports: " + ", ".join(m["imports"]))
        for s in m["classes"] + m["functions"]:
            out.append(f"  {s['signature']} @{s['line']}" + (f" - {s['doc']}" if s["doc"] else ""))
    return "\n".join(out) + "\n"


def write(root: Path, out_dir: Path, roots: tuple[str, ...] = ROOTS) -> tuple[str, dict]:
    data = build(root, roots)
    text = render(data)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "MAP.md").write_bytes(text.encode("utf-8"))
    blob = json.dumps(data, indent=1, sort_keys=True, ensure_ascii=False) + "\n"
    (out_dir / "map.json").write_bytes(blob.encode("utf-8"))
    return text, data


def main(argv: list[str] | None = None) -> int:
    here = Path(__file__).resolve().parents[1]
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=here)
    ap.add_argument("--out", type=Path, default=None)
    args = ap.parse_args(argv)
    out = args.out or args.root / "build" / "codemap"
    text, data = write(args.root, out)
    print(f"MAP.md: {len(text.splitlines())} lines, modules: {len(data['modules'])}, unparsed: {len(data['unparsed'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
